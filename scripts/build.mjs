/**
 * Build client.js: bundle src/client/index.ts as CommonJS with React left
 * external, then wrap it in the lazy factory the Harness module loader expects
 * (`window.__ModuleLoader__.load({ id, factory(require) })`). The loader's
 * `require` answers `react` from the platform module table.
 *
 *   node scripts/build.mjs           write client.js
 *   node scripts/build.mjs --check   fail when client.js is stale
 */
import { build } from 'esbuild'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))
const check = process.argv.includes('--check')

const result = await build({
  entryPoints: [join(root, 'src/client/index.ts')],
  bundle: true,
  write: false,
  format: 'cjs',
  platform: 'browser',
  target: 'es2022',
  external: ['react'],
  jsx: 'transform',
  jsxFactory: 'React.createElement',
  jsxFragment: 'React.Fragment',
  legalComments: 'none',
  charset: 'utf8',
  logLevel: 'warning',
})
const body = result.outputFiles[0].text

const out = `/**
 * ${pkg.name} ${pkg.version} — browser half (generated by scripts/build.mjs from src/; do not edit).
 * Loaded by the Harness module loader as the package's "./client" export.
 */
window.__ModuleLoader__.load({
\tid: ${JSON.stringify(pkg.name)},
\tfactory: (require) => {
\t\tvar module = { exports: {} };
\t\tvar exports = module.exports;
${body}
\t\treturn module.exports;
\t}
});
`

const target = join(root, 'client.js')
if (check) {
  let current = ''
  try { current = readFileSync(target, 'utf8') } catch { /* missing counts as stale */ }
  if (current !== out) {
    console.error('client.js is stale: run `node scripts/build.mjs`')
    process.exit(1)
  }
  console.log('client.js is up to date')
} else {
  writeFileSync(target, out)
  console.log(`wrote client.js (${(out.length / 1024).toFixed(1)} KiB)`)
}
